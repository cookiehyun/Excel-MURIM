def sanmun(W, H):
    """Dawn courtyard on a mountain top (mountain gate)."""
    s = Stage(W, H, {
        "0": "1E1B3A", "1": "2A2550", "2": "3D2F63", "3": "5A3A6E",
        "4": "804670", "5": "A8566A", "6": "CF7262", "7": "E8955A",
        "u": "F7D9A0", "U": "FBE9C4",
        "f": "7A5F86", "F": "8C6E93", "m": "4F4672", "M": "5E5480",
        "n": "2E3052", "N": "393B5E", "z": "A98AA8",
        "t": "1C1C33", "y": "C9503A",
        "g": "1F3A34", "G": "2C5045", "T": "3B2A26",
        "r": "8A7A6A", "R": "6A5C50", "q": "A89780",
        "s": "7D6E5E", "S": "6B5D4F", "e": "9C8B74", "d": "4E433A",
    })
    s.sky("01234567", 0, s.Y(50))
    s.disc(86, 23, 7.5, "U", rim="u")
    s.ridge("f", "F", 33, [(5, 0.07, 0.3), (2.5, 0.19, 1.7), (1.0, 0.5, 0.2)])
    for dy in (38, 39, 42):                                   # mist over the far range
        y = s.Y(dy)
        for x in range(W):
            if (int(x / s.sx) // 6 + dy) % 3 != 0 and s.g[y][x] in ("f", "F"):
                s.g[y][x] = "z"
    mid = s.ridge("m", "M", 40, [(5, 0.05, 2.0), (2.0, 0.23, 0.4), (0.8, 0.61, 1.1)])
    s.ridge("n", "N", 46, [(3, 0.045, 4.0), (1.5, 0.17, 2.2), (0.7, 0.7, 0.5)])
    # pagoda on the mid ridge
    px = 22
    base = mid[s.X(px)] / s.sy
    for w, dy in ((9, 0), (7, -4), (5, -8), (3, -11)):
        s.rect(px - w / 2, base + dy - 3, w, 3.2, "t")
        s.rect(px - w / 2 - 1, base + dy - 3, w + 2, 1, "t")        # eaves
        s.rect(px - 0.4, base + dy - 1.6, 0.9, 0.9, "y")
    s.rect(px - 0.4, base - 15, 0.9, 4, "t")
    # pine tree (right)
    tx = 108
    s.rect(tx, 20, 2, DGROUND - 20, "T")
    for cy, half in ((22, 9), (28, 11), (34, 8), (40, 10)):
        for dy in range(-2, 3):
            span = half - abs(dy) * 2
            s.rect(tx - span, cy + dy, span * 1.5 + 2, 1, "G" if dy == -2 else "g")
    for dx in range(96, 108):
        s.rect(dx, 30 + (108 - dx) // 5, 1, 1, "T")
    # stone railing
    rail = 50
    s.rect(0, rail, DW, 1, "q")
    s.rect(0, rail + 1, DW, 1, "r")
    for dx in range(0, DW, 12):
        s.rect(dx, rail - 1, 1, DGROUND - rail + 1, "r")
        s.rect(dx + 1, rail - 1, 1, DGROUND - rail + 1, "R")
        s.rect(dx, rail - 1, 2, 1, "q")
    for dx in range(6, DW, 12):
        for k in (-4, 0, 4):
            s.rect(dx + k, rail + 2, 0.6, DGROUND - rail - 2, "R")
    floor(s, "s", "S", "e", "d")
    return s


def floor(s, base, seam, edge, joint):
    """stone floor below the ground line with staggered tile joints"""
    for y in range(s.ground, s.H):
        s.g[y] = [base] * s.W
    s.g[s.ground] = [edge] * s.W
    rows = s.H - s.ground
    seams = [s.ground + max(2, round(rows * f)) for f in (0.33, 0.7)]
    for y in seams:
        if y < s.H:
            s.g[y] = [seam] * s.W
    tile = max(8, s.X(16))
    for y in range(s.ground + 1, s.H):
        band = sum(1 for sy in seams if y > sy)
        offs = (0, tile // 2, tile // 4)[band]
        for x in range(s.W):
            if (x + offs) % tile == 0 and s.g[y][x] == base:
                s.g[y][x] = joint


def bamboo(W, H):
    """Misty bamboo forest in the morning."""
    s = Stage(W, H, {
        "0": "2F5650", "1": "3F6B62", "2": "547F72", "3": "6C9483", "4": "88AA95", "5": "A6C2AB",
        "a": "8FB09A", "A": "9DBBA4",                 # far bamboo (misty)
        "b": "4E7A55", "B": "64905F", "n": "3A5E40",  # mid bamboo / node
        "v": "3F6B3C", "V": "5A8A4A",                 # leaves
        "c": "2F5A2E", "C": "4C7F3A", "D": "6E9F4F", "N": "1F3D20",   # foreground bamboo
        "k": "6F7A70", "K": "8C978C", "j": "4F5A52", "w": "F2D27A",   # stone lantern
        "s": "6B5A3E", "S": "58492F", "e": "7E7048", "d": "463A26",   # dirt floor
        "g": "5C7A3A", "G": "7A9A48", "f": "A0743A",                  # grass / fallen leaves
    })
    s.sky("012345", 0, s.ground)

    def stalk(dx, dw, top, col, hi, node, spacing, phase=0):
        x0, x1 = s.X(dx), max(s.X(dx) + 1, s.X(dx + dw))
        for y in range(s.Y(top), s.ground):
            for x in range(x0, x1):
                s.put(x, y, hi if (x == x0 and x1 - x0 >= 2) else col)
        y = s.Y(top) + int(phase * s.sy)
        while y < s.ground:
            for x in range(x0 - (1 if x1 - x0 >= 3 else 0), x1 + (1 if x1 - x0 >= 3 else 0)):
                s.put(x, y, node)
            y += max(3, s.Y(spacing))

    def leaves(dcx, dcy, n, col, hi, spread=7):
        import random
        rnd = random.Random(int(dcx * 31 + dcy))
        for _ in range(n):
            lx = dcx + rnd.uniform(-spread, spread)
            ly = dcy + rnd.uniform(-spread * 0.45, spread * 0.45)
            d = rnd.choice((-1, 1))
            for k in range(4):                         # one diagonal leaf stroke
                c = hi if k == 0 else col
                s.put(s.X(lx + k * 0.9 * d), s.Y(ly + k * 0.45), c)
                s.put(s.X(lx + k * 0.9 * d) + 1, s.Y(ly + k * 0.45), c)

    # far misty bamboo
    for dx in (4, 13, 21, 33, 41, 58, 66, 83, 92, 101, 113):
        stalk(dx, 1.2, 0, "a", "a", "A", 9, dx % 5)
    # mid bamboo with leaves
    for dx, ph in ((9, 1), (27, 3), (47, 0), (71, 2), (88, 4), (107, 1)):
        stalk(dx, 2.2, 0, "b", "B", "n", 11, ph)
        for ly in (6, 18, 31):
            leaves(dx + 1, ly + ph, 7, "v", "V")
    # stone lantern (left of center)
    lx = 36
    s.rect(lx - 3.5, DGROUND - 14, 7, 1.5, "K")        # roof
    s.rect(lx - 2.5, DGROUND - 15, 5, 1, "k")
    s.rect(lx - 2, DGROUND - 12.5, 4, 3.5, "k")        # light box
    s.rect(lx - 1, DGROUND - 11.5, 2, 1.8, "w")
    s.rect(lx - 1, DGROUND - 9, 2, 6, "j")             # pillar
    s.rect(lx - 3, DGROUND - 3, 6, 3, "k")             # base
    s.rect(lx - 3, DGROUND - 3, 6, 0.8, "K")
    # foreground bamboo at both edges
    for dx, dw, ph in ((1, 4, 2), (7.5, 3, 6), (110, 3.5, 4), (115.5, 4.5, 0)):
        stalk(dx, dw, 0, "c", "D", "N", 13, ph)
        x0 = s.X(dx + dw * 0.6)
        for y in range(0, s.ground):                    # inner highlight stripe
            if s.g[y][x0] == "c":
                s.g[y][x0] = "C"
    for dx in (5, 113):
        for ly in (3, 14):
            leaves(dx, ly, 12, "c", "C", 9)
    floor_dirt(s)
    return s


def floor_dirt(s):
    """packed earth path with grass tufts and fallen leaves"""
    import random
    rnd = random.Random(7)
    for y in range(s.ground, s.H):
        s.g[y] = ["s"] * s.W
    s.g[s.ground] = ["e"] * s.W
    rows = s.H - s.ground
    for y in (s.ground + max(2, round(rows * 0.45)),):
        for x in range(s.W):
            if (x // 3) % 4 != 0:
                s.g[y][x] = "S"
    for _ in range(s.W // 3):                           # pebbles / dark spots
        x, y = rnd.randrange(s.W), rnd.randrange(s.ground + 2, s.H)
        s.g[y][x] = "d"
    for _ in range(s.W // 6):                           # fallen leaves
        x, y = rnd.randrange(s.W - 1), rnd.randrange(s.ground + 1, s.H)
        s.g[y][x] = "f"; s.g[y][x + 1] = "f"
    x = 0
    while x < s.W:                                      # grass tufts on the ground line
        if rnd.random() < 0.35:
            for k in range(rnd.randint(2, 4)):
                if x + k < s.W:
                    s.g[s.ground - 1][x + k] = "g" if k % 2 else "G"
                    if k == 1:
                        s.g[s.ground - 2][x + k] = "G"
        x += rnd.randint(3, 7)


def inn(W, H):
    """Wuxia inn (kezhan) at night, seen up close: wide hall, central upper pavilion, lanterns under the eaves."""
    import random
    rnd = random.Random(3)
    s = Stage(W, H, {
        "0": "0B1026", "1": "121938", "2": "1B2349", "*": "C8D0F0", "m": "E8E2C0",
        "M": "3E4C78", "N": "56669A",                                         # distant mountains (lit by the moon)
        "r": "2E4450", "R": "22343E", "x": "6A8494", "z": "18242C",           # roof tiles / grooves / eave edge / ridge
        "g": "D4A848",                                                        # gold ornaments
        "p": "A02C22", "P": "6E1C18", "b": "B8402C",                          # red pillars / shadow / beams
        "c": "2F7A6A", "C": "48A08A",                                         # teal brackets
        "w": "3E2820", "y": "F2C46A", "Y": "B07A34",                          # wall / lit lattice / lattice bars
        "o": "1A1014",                                                        # doorway
        "h": "141018",                                                        # plaque
        "l": "D8342A", "L": "FF8A50", "t": "1A1218",                          # lanterns / glow / cord
        "s": "6E6658", "S": "5A5348", "e": "8E8676", "d": "3E3830", "u": "7E7060",   # stone
    })
    s.sky("012", 0, s.ground)
    for _ in range(36):
        s.put(rnd.randrange(W), rnd.randrange(s.Y(14)), "*")
    s.disc(14, 6, 3.2, "m")
    s.ridge("M", "N", 17, [(4, 0.09, 1.0), (2.5, 0.23, 0.3), (1, 0.6, 2.0)], bottom=s.Y(30))

    cx = 60
    def roof(half, top, height, overhang, lift):
        """sweeping roof centred on cx: ridge at top, eave line curving up at both ends"""
        x0, x1 = s.X(cx - half - overhang), s.X(cx + half + overhang)
        hw = (half + overhang) * s.sx
        for x in range(x0, x1 + 1):
            t = abs(x + 0.5 - s.X(cx)) / hw                  # 0 centre .. 1 tip
            curl = max(0.0, (t - 0.55) / 0.45) ** 2
            yb = s.Y(top + height) - int(round(lift * s.sy * curl))
            yt = s.Y(top) + int(round((height * 0.35) * s.sy * t)) - int(round(lift * 0.6 * s.sy * curl))
            for y in range(max(0, yt), yb + 1):
                groove = (int(x / s.sx) % 3 == 0)
                s.put(x, y, "R" if groove else "r")
            s.put(x, yb, "x")                                # tile ends along the eave
            if yb + 1 < s.ground:
                s.put(x, yb + 1, "z")
        # ridge + end ornaments
        s.rect(cx - half * 0.75, top - 1.2, half * 1.5, 1.2, "z")
        for sgn in (-1, 1):
            ex = cx + sgn * half * 0.75
            s.rect(ex - 0.8, top - 3, 1.6, 2, "g")
            s.rect(ex + sgn * 0.8 - 0.4, top - 3.6, 0.9, 1, "g")
            tip = cx + sgn * (half + overhang)
            s.rect(tip - 0.8, top + height - lift - 1.2, 1.6, 1.2, "g")

    def brackets(x0, x1, y):
        s.rect(x0, y, x1 - x0, 1, "b")
        dx = x0 + 1
        while dx < x1 - 1:
            s.rect(dx, y + 1, 2, 1, "c")
            s.rect(dx + 0.5, y + 2, 1, 0.8, "C")
            dx += 4

    def lattice(x0, y0, w, h):
        s.rect(x0, y0, w, h, "Y")
        s.rect(x0 + 0.6, y0 + 0.6, w - 1.2, h - 1.2, "y")
        k = x0 + 2
        while k < x0 + w - 1:
            s.rect(k, y0 + 0.6, 0.5, h - 1.2, "Y")
            k += 2
        k = y0 + 2
        while k < y0 + h - 1:
            s.rect(x0 + 0.6, k, w - 1.2, 0.5, "Y")
            k += 2.4

    # ---- upper storey
    s.rect(cx - 36, 15, 72, 13, "w")
    for px in (-36, -20, 18.6, 34.6):
        s.rect(cx + px, 15, 1.4, 13, "p")
    for wx in (-31, -17, 9, 23):
        lattice(cx + wx, 18, 8, 8)
    s.rect(cx - 6, 17, 12, 6, "g")                            # plaque
    s.rect(cx - 5.2, 17.8, 10.4, 4.4, "h")
    s.rect(cx - 3.2, 19.4, 1.4, 1.2, "g"); s.rect(cx + 1.8, 19.4, 1.4, 1.2, "g")
    brackets(cx - 37, cx + 37, 13.5)
    roof(34, 4, 10, 9, 4.5)
    # ---- lower storey (taller, wider)
    s.rect(-2, 33, DW + 4, DGROUND - 33 - 3, "w")
    for px in (-58, -42, -26, -10, 9, 25, 41, 57):
        s.rect(cx + px, 33, 1.6, DGROUND - 36, "p")
        s.rect(cx + px + 1.1, 33, 0.5, DGROUND - 36, "P")
    for wx in (-53, -37, -21, 14, 30, 46):
        lattice(cx + wx, 38, 8, 9)
    s.rect(cx - 7, 37, 14, DGROUND - 40, "o")                 # doorway
    s.rect(cx - 8, 36, 16, 1.2, "b")
    s.rect(cx - 8, 36, 1.2, DGROUND - 39, "p"); s.rect(cx + 6.8, 36, 1.2, DGROUND - 39, "p")
    brackets(-2, DW + 2, 31.5)
    roof(62, 26, 5.5, 4, 3.5)
    # stone platform + steps
    s.rect(-2, DGROUND - 3, DW + 4, 3, "S")
    s.rect(-2, DGROUND - 3, DW + 4, 0.8, "e")
    s.rect(cx - 9, DGROUND - 2, 18, 1, "e")
    s.rect(cx - 10, DGROUND - 1, 20, 1, "e")

    # lanterns hanging under the upper eaves (well above head height)
    for lx in (cx - 40, cx - 26, cx + 26, cx + 40):
        top = 14 if abs(lx - cx) > 30 else 15
        s.rect(lx - 0.25, top, 0.5, 2.5, "t")
        y0 = top + 2.5
        s.rect(lx - 1.4, y0, 2.8, 0.7, "g")
        s.rect(lx - 2, y0 + 0.7, 4, 3.2, "l")
        s.rect(lx - 1.4, y0 + 0.2, 2.8, 4.2, "l")
        s.rect(lx - 0.7, y0 + 1.2, 1.4, 2.2, "L")
        s.rect(lx - 1.4, y0 + 3.9, 2.8, 0.7, "g")
        s.rect(lx - 0.3, y0 + 4.6, 0.6, 1.6, "g")

    floor(s, "s", "S", "e", "d")
    for lx in (cx - 44, cx - 22, cx, cx + 22, cx + 44):       # warm light on the courtyard
        for y in range(s.ground + 1, min(s.H, s.ground + 3)):
            for x in range(s.X(lx - 8), s.X(lx + 8)):
                if 0 <= x < W and s.g[y][x] == "s":
                    s.g[y][x] = "u"
    return s


