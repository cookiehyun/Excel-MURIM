"""Stage backgrounds -> data/stage_<name>.txt + docs/preview/stage_<name>.png

Every stage is drawn in "design units" of a 120 x 64 screen and scaled to the
real screen size (W x H), so the same stage works at any resolution.
Colors are kept in few flat bands on purpose: fewer distinct runs per row means
fewer Range paint calls in Excel.

usage: python tools/gen_stages.py [W H] [stage names...]
       (defaults: 192 100 = Renderer.SCREEN_W/H, all stages)
"""
import math
import os
import sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DW, DH = 120, 64          # design units
DGROUND = 56              # design ground row


class Stage:
    def __init__(self, W, H, pal):
        self.W, self.H = W, H
        self.sx, self.sy = W / DW, H / DH
        self.ground = round(DGROUND * self.sy)
        self.pal = pal
        self.g = [["0"] * W for _ in range(H)]

    # design -> screen
    def X(self, dx):
        return int(round(dx * self.sx))

    def Y(self, dy):
        return int(round(dy * self.sy))

    def put(self, x, y, c):
        if 0 <= x < self.W and 0 <= y < self.H:
            self.g[y][x] = c

    def rect(self, dx, dy, dw, dh, c):
        """rectangle in design units"""
        for y in range(self.Y(dy), self.Y(dy + dh)):
            for x in range(self.X(dx), self.X(dx + dw)):
                self.put(x, y, c)

    def sky(self, bands, top=0, bottom=None):
        """vertical gradient in flat bands from row top to bottom (screen rows)"""
        bottom = self.ground if bottom is None else bottom
        n = len(bands)
        for y in range(top, bottom):
            t = (y - top) / max(1, bottom - top - 1)
            c = bands[min(n - 1, int(t * n))]
            self.g[y] = [c] * self.W

    def disc(self, dcx, dcy, dr, c, rim=None, rim_w=2.2):
        cx, cy, r = dcx * self.sx, dcy * self.sy, dr * self.sy
        for y in range(self.H):
            for x in range(self.W):
                d = math.hypot(x + 0.5 - cx, y + 0.5 - cy)
                if d <= r:
                    self.g[y][x] = c if (rim is None or d <= r - rim_w * self.sy) else rim

    def ridge(self, col, lit, base, amps, bottom=None):
        """mountain silhouette; base/amps in design units, freq per design px"""
        bottom = self.ground if bottom is None else bottom
        tops = []
        for x in range(self.W):
            dx = x / self.sx
            v = base
            for a, f, ph in amps:
                v += a * math.sin(dx * f + ph)
            top = self.Y(v)
            tops.append(top)
            for y in range(max(0, top), bottom):
                self.g[y][x] = col
        for x in range(1, self.W):
            if 0 <= tops[x] < bottom and (tops[x] < tops[x - 1] or (x * 7) % 3 == 0):
                self.g[tops[x]][x] = lit
        return tops

    def save(self, name, out_dir=None):
        out_dir = out_dir or os.path.join(ROOT, "data")
        prev_dir = out_dir if out_dir != os.path.join(ROOT, "data") else os.path.join(ROOT, "docs", "preview")
        lines = [f"# stage background - generated by tools/gen_stages.py, do not edit by hand",
                 "# PAL <char> <RRGGBB> ; STAGE <name> <w> <h> <groundY> ; rows"]
        for k, v in self.pal.items():
            lines.append(f"PAL {k} {v}")
        lines.append(f"STAGE {name} {self.W} {self.H} {self.ground}")
        runs = 0
        for row in self.g:
            lines.append("".join(row))
            runs += 1 + sum(1 for i in range(1, self.W) if row[i] != row[i - 1])
        with open(os.path.join(out_dir, f"stage_{name}.txt"), "w", newline="\r\n") as f:
            f.write("\n".join(lines) + "\n")
        img = self.image()
        img.resize((self.W * 6, self.H * 6), Image.NEAREST).save(os.path.join(prev_dir, f"stage_{name}.png"))
        return runs

    def image(self):
        img = Image.new("RGB", (self.W, self.H))
        px = img.load()
        for y in range(self.H):
            for x in range(self.W):
                h = self.pal[self.g[y][x]]
                px[x, y] = (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
        return img


