def sanmun(W, H):
    """Dawn courtyard on a mountain top (mountain gate)."""
    s = Stage(W, H, {
        "0": "1E1B3A", "1": "2A2550", "2": "3D2F63", "3": "5A3A6E",
        "4": "804670", "5": "A8566A", "6": "CF7262", "7": "E8955A",
        "u": "F7D9A0", "U": "FBE9C4",
        "f": "7A5F86", "F": "8C6E93", "m": "4F4672", "M": "5E5480",
        "n": "2E3052", "N": "393B5E", "z": "A98AA8",
        "t": "1C1C33", "y": "C9503A",
        "g": "1F3A34", "G": "2C5045", "T": "3B2A26",
        "r": "8A7A6A", "R": "6A5C50", "q": "A89780",
        "s": "7D6E5E", "S": "6B5D4F", "e": "9C8B74", "d": "4E433A",
    })
    s.sky("01234567", 0, s.Y(50))
    s.disc(86, 23, 7.5, "U", rim="u")
    s.ridge("f", "F", 33, [(5, 0.07, 0.3), (2.5, 0.19, 1.7), (1.0, 0.5, 0.2)])
    for dy in (38, 39, 42):                                   # mist over the far range
        y = s.Y(dy)
        for x in range(W):
            if (int(x / s.sx) // 6 + dy) % 3 != 0 and s.g[y][x] in ("f", "F"):
                s.g[y][x] = "z"
    mid = s.ridge("m", "M", 40, [(5, 0.05, 2.0), (2.0, 0.23, 0.4), (0.8, 0.61, 1.1)])
    s.ridge("n", "N", 46, [(3, 0.045, 4.0), (1.5, 0.17, 2.2), (0.7, 0.7, 0.5)])
    # pagoda on the mid ridge
    px = 22
    base = mid[s.X(px)] / s.sy
    for w, dy in ((9, 0), (7, -4), (5, -8), (3, -11)):
        s.rect(px - w / 2, base + dy - 3, w, 3.2, "t")
        s.rect(px - w / 2 - 1, base + dy - 3, w + 2, 1, "t")        # eaves
        s.rect(px - 0.4, base + dy - 1.6, 0.9, 0.9, "y")
    s.rect(px - 0.4, base - 15, 0.9, 4, "t")
    # pine tree (right)
    tx = 108
    s.rect(tx, 20, 2, DGROUND - 20, "T")
    for cy, half in ((22, 9), (28, 11), (34, 8), (40, 10)):
        for dy in range(-2, 3):
            span = half - abs(dy) * 2
            s.rect(tx - span, cy + dy, span * 1.5 + 2, 1, "G" if dy == -2 else "g")
    for dx in range(96, 108):
        s.rect(dx, 30 + (108 - dx) // 5, 1, 1, "T")
    # stone railing
    rail = 50
    s.rect(0, rail, DW, 1, "q")
    s.rect(0, rail + 1, DW, 1, "r")
    for dx in range(0, DW, 12):
        s.rect(dx, rail - 1, 1, DGROUND - rail + 1, "r")
        s.rect(dx + 1, rail - 1, 1, DGROUND - rail + 1, "R")
        s.rect(dx, rail - 1, 2, 1, "q")
    for dx in range(6, DW, 12):
        for k in (-4, 0, 4):
            s.rect(dx + k, rail + 2, 0.6, DGROUND - rail - 2, "R")
    floor(s, "s", "S", "e", "d")
    return s


def floor(s, base, seam, edge, joint):
    """stone floor below the ground line with staggered tile joints"""
    for y in range(s.ground, s.H):
        s.g[y] = [base] * s.W
    s.g[s.ground] = [edge] * s.W
    rows = s.H - s.ground
    seams = [s.ground + max(2, round(rows * f)) for f in (0.33, 0.7)]
    for y in seams:
        if y < s.H:
            s.g[y] = [seam] * s.W
    tile = max(8, s.X(16))
    for y in range(s.ground + 1, s.H):
        band = sum(1 for sy in seams if y > sy)
        offs = (0, tile // 2, tile // 4)[band]
        for x in range(s.W):
            if (x + offs) % tile == 0 and s.g[y][x] == base:
                s.g[y][x] = joint


def bamboo(W, H):
    """Misty bamboo forest in the morning."""
    s = Stage(W, H, {
        "0": "2F5650", "1": "3F6B62", "2": "547F72", "3": "6C9483", "4": "88AA95", "5": "A6C2AB",
        "a": "8FB09A", "A": "9DBBA4",                 # far bamboo (misty)
        "b": "4E7A55", "B": "64905F", "n": "3A5E40",  # mid bamboo / node
        "v": "3F6B3C", "V": "5A8A4A",                 # leaves
        "c": "2F5A2E", "C": "4C7F3A", "D": "6E9F4F", "N": "1F3D20",   # foreground bamboo
        "k": "6F7A70", "K": "8C978C", "j": "4F5A52", "w": "F2D27A",   # stone lantern
        "s": "6B5A3E", "S": "58492F", "e": "7E7048", "d": "463A26",   # dirt floor
        "g": "5C7A3A", "G": "7A9A48", "f": "A0743A",                  # grass / fallen leaves
    })
    s.sky("012345", 0, s.ground)

    def stalk(dx, dw, top, col, hi, node, spacing, phase=0):
        x0, x1 = s.X(dx), max(s.X(dx) + 1, s.X(dx + dw))
        for y in range(s.Y(top), s.ground):
            for x in range(x0, x1):
                s.put(x, y, hi if (x == x0 and x1 - x0 >= 2) else col)
        y = s.Y(top) + int(phase * s.sy)
        while y < s.ground:
            for x in range(x0 - (1 if x1 - x0 >= 3 else 0), x1 + (1 if x1 - x0 >= 3 else 0)):
                s.put(x, y, node)
            y += max(3, s.Y(spacing))

    def leaves(dcx, dcy, n, col, hi, spread=7):
        import random
        rnd = random.Random(int(dcx * 31 + dcy))
        for _ in range(n):
            lx = dcx + rnd.uniform(-spread, spread)
            ly = dcy + rnd.uniform(-spread * 0.45, spread * 0.45)
            d = rnd.choice((-1, 1))
            for k in range(4):                         # one diagonal leaf stroke
                c = hi if k == 0 else col
                s.put(s.X(lx + k * 0.9 * d), s.Y(ly + k * 0.45), c)
                s.put(s.X(lx + k * 0.9 * d) + 1, s.Y(ly + k * 0.45), c)

    # far misty bamboo
    for dx in (4, 13, 21, 33, 41, 58, 66, 83, 92, 101, 113):
        stalk(dx, 1.2, 0, "a", "a", "A", 9, dx % 5)
    # mid bamboo with leaves
    for dx, ph in ((9, 1), (27, 3), (47, 0), (71, 2), (88, 4), (107, 1)):
        stalk(dx, 2.2, 0, "b", "B", "n", 11, ph)
        for ly in (6, 18, 31):
            leaves(dx + 1, ly + ph, 7, "v", "V")
    # stone lantern (left of center)
    lx = 36
    s.rect(lx - 3.5, DGROUND - 14, 7, 1.5, "K")        # roof
    s.rect(lx - 2.5, DGROUND - 15, 5, 1, "k")
    s.rect(lx - 2, DGROUND - 12.5, 4, 3.5, "k")        # light box
    s.rect(lx - 1, DGROUND - 11.5, 2, 1.8, "w")
    s.rect(lx - 1, DGROUND - 9, 2, 6, "j")             # pillar
    s.rect(lx - 3, DGROUND - 3, 6, 3, "k")             # base
    s.rect(lx - 3, DGROUND - 3, 6, 0.8, "K")
    # foreground bamboo at both edges
    for dx, dw, ph in ((1, 4, 2), (7.5, 3, 6), (110, 3.5, 4), (115.5, 4.5, 0)):
        stalk(dx, dw, 0, "c", "D", "N", 13, ph)
        x0 = s.X(dx + dw * 0.6)
        for y in range(0, s.ground):                    # inner highlight stripe
            if s.g[y][x0] == "c":
                s.g[y][x0] = "C"
    for dx in (5, 113):
        for ly in (3, 14):
            leaves(dx, ly, 12, "c", "C", 9)
    floor_dirt(s)
    return s


def floor_dirt(s):
    """packed earth path with grass tufts and fallen leaves"""
    import random
    rnd = random.Random(7)
    for y in range(s.ground, s.H):
        s.g[y] = ["s"] * s.W
    s.g[s.ground] = ["e"] * s.W
    rows = s.H - s.ground
    for y in (s.ground + max(2, round(rows * 0.45)),):
        for x in range(s.W):
            if (x // 3) % 4 != 0:
                s.g[y][x] = "S"
    for _ in range(s.W // 3):                           # pebbles / dark spots
        x, y = rnd.randrange(s.W), rnd.randrange(s.ground + 2, s.H)
        s.g[y][x] = "d"
    for _ in range(s.W // 6):                           # fallen leaves
        x, y = rnd.randrange(s.W - 1), rnd.randrange(s.ground + 1, s.H)
        s.g[y][x] = "f"; s.g[y][x + 1] = "f"
    x = 0
    while x < s.W:                                      # grass tufts on the ground line
        if rnd.random() < 0.35:
            for k in range(rnd.randint(2, 4)):
                if x + k < s.W:
                    s.g[s.ground - 1][x + k] = "g" if k % 2 else "G"
                    if k == 1:
                        s.g[s.ground - 2][x + k] = "G"
        x += rnd.randint(3, 7)


def inn(W, H):
    """Inn courtyard at night, paper lanterns strung across."""
    import random
    rnd = random.Random(3)
    s = Stage(W, H, {
        "0": "0B1026", "1": "121938", "2": "1B2349", "*": "C8D0F0",        # sky, stars
        "m": "E8E2C0",                                                       # moon
        "r": "2A1E2A", "R": "3A2A36", "x": "4A3A48",                         # roof tiles / ridge / eave tips
        "w": "4A3024", "W": "5E3E2C", "q": "3A251C",                         # timber wall / beams
        "y": "F2C46A", "Y": "D89A40", "p": "8A5A30",                         # lit paper window / frame
        "o": "1A1014",                                                       # open doorway (dark)
        "h": "6A2A20", "H": "C89A40",                                        # plaque / plaque rim
        "l": "D83A2A", "L": "FF7A4A", "t": "1A1218",                         # lanterns / glow / string
        "b": "5A3A22", "B": "7A5230", "k": "2E1E14",                         # barrels
        "s": "4E4038", "S": "3E322C", "e": "7A6248", "d": "2E2620", "u": "6A5444",  # floor (warm lit)
    })
    s.sky("012", 0, s.ground)
    for _ in range(40):
        x, y = rnd.randrange(W), rnd.randrange(s.Y(12))
        s.put(x, y, "*")
    s.disc(104, 7, 3.5, "m")
    # distant rooftops beside the inn
    for bx, bw, top in ((-4, 18, 30), (104, 20, 26)):
        s.rect(bx, top, bw, DGROUND - top, "q")
        s.rect(bx - 2, top - 2, bw + 4, 2, "r")
        s.rect(bx - 3, top - 3, 2, 1, "x"); s.rect(bx + bw + 1, top - 3, 2, 1, "x")
        s.rect(bx + 4, top + 4, 4, 3, "Y")
    # building
    left, right = 10, 110
    s.rect(left, 16, right - left, DGROUND - 16, "w")                       # walls
    for dy in (16, 30, 31):                                                  # floor beams
        s.rect(left, dy, right - left, 1, "q")
    for dx in range(left, right + 1, 20):                                    # posts
        s.rect(dx - 0.6, 16, 1.3, DGROUND - 16, "q")
    # upper roof with curved eaves
    for dy in range(0, 6):
        inset = 6 - dy
        s.rect(left - 6 + inset * 0.6, 10 + dy, right - left + 12 - inset * 1.2, 1, "r" if dy % 2 else "R")
    for k in range(3):                                                       # upturned eave tips
        s.rect(left - 6 - k * 1.2, 14 - k * 1.6, 2, 1.6, "x")
        s.rect(right + 4 + k * 1.2, 14 - k * 1.6, 2, 1.6, "x")
    s.rect(left - 2, 9, right - left + 4, 1, "R")                            # ridge
    s.rect(46, 7.5, 28, 1.5, "R")
    # lower roof over the balcony
    for dy in range(0, 3):
        s.rect(left - 3 + dy, 32 + dy, right - left + 6 - dy * 2, 1, "r" if dy % 2 else "R")
    for k in range(2):
        s.rect(left - 4 - k, 33 - k * 1.2, 1.6, 1.2, "x")
        s.rect(right + 2.4 + k, 33 - k * 1.2, 1.6, 1.2, "x")
    # upper windows (lit paper, lattice)
    for dx in (16, 36, 76, 96):
        s.rect(dx, 19, 9, 8, "p")
        s.rect(dx + 0.8, 19.8, 7.4, 6.4, "y")
        for k in (3, 5.7):
            s.rect(dx + k, 19.8, 0.6, 6.4, "Y")
        s.rect(dx + 0.8, 22.8, 7.4, 0.6, "Y")
    # plaque in the middle
    s.rect(52, 19, 16, 7, "H")
    s.rect(53, 20, 14, 5, "h")
    for k in range(3):
        s.rect(55.5 + k * 3.5, 21.2, 1.6, 2.6, "H")
    # ground floor: doorway + lit windows
    s.rect(54, 39, 12, DGROUND - 39, "o")
    s.rect(53, 38, 14, 1, "q")
    for dx in (20, 82):
        s.rect(dx, 40, 14, 9, "p")
        s.rect(dx + 0.8, 40.8, 12.4, 7.4, "y")
        for k in (4, 8.3):
            s.rect(dx + k, 40.8, 0.6, 7.4, "Y")
    # lantern string + lanterns
    for x in range(W):                                                       # continuous string
        s.put(x, s.Y(26 + 5 * math.sin(math.pi * (x / s.sx) / DW)), "t")
    for dx in range(0, DW):
        sag = 26 + 5 * math.sin(math.pi * dx / DW)
        if dx % 16 == 8:
            cx, cy = dx, sag + 1
            s.rect(cx - 1.6, cy, 3.2, 4.2, "l")
            s.rect(cx - 0.6, cy + 0.8, 1.2, 2.6, "L")
            s.rect(cx - 1.0, cy - 0.4, 2, 0.6, "t")
            s.rect(cx - 0.3, cy + 4.2, 0.6, 1.2, "Y")
    # barrels (left) and a stack (right)
    for bx, by in ((2, DGROUND - 7), (8, DGROUND - 7), (5, DGROUND - 13), (113, DGROUND - 7)):
        s.rect(bx, by, 5, 7, "b")
        s.rect(bx + 0.6, by, 1.2, 7, "B")
        for k in (1, 5.4):
            s.rect(bx, by + k, 5, 0.6, "k")
    floor(s, "s", "S", "e", "d")
    # warm light pools under the windows / door
    for cx in (27, 60, 89):
        for y in range(s.ground + 1, min(s.H, s.ground + 4)):
            half = s.X(7) + (y - s.ground) * 2
            for x in range(s.X(cx) - half, s.X(cx) + half):
                if 0 <= x < W and s.g[y][x] == "s":
                    s.g[y][x] = "u"
    return s


